-- 0018: отчётные периоды — когда команда последний раз «обнулилась»
--
-- КОНТЕКСТ (22.10.2026). Владелец и оператор работают отчётными периодами (обычно
-- календарный месяц): в конце подводят итог — сколько сделано Furious €30, €105,
-- Massive €100 — и делят заработанное. Расчёт часто сдвигают на день-два, поэтому
-- период кончается не по календарю, а кнопкой «✅ Расчёт произведён» в боте.
--
-- ИТОГИ НЕ ХРАНИМ — они пересчитываются из purchases (period-calc.ts), как баланс
-- карты (0017): ↩️ удаление покупки или правка задним числом не разъедутся с итогом.
-- Храним только границы: строка = начало нового периода (момент обнуления и кто).
-- Пока строк нет, первый период начинается 21.09.2026 00:00 МСК (решение владельца,
-- константа FIRST_PERIOD_START в коде) — строку-сид не вставляем, чтобы
-- восстановление из бэкапа не упиралось в неё.
--
-- Уникальность started_at — страховка от двойного нажатия: второе обнуление в ту же
-- миллисекунду невозможно, а повтор нажатия бот отсекает сам (сверяет id периода).
--
-- RLS включаем, как на всех рабочих таблицах (политик нет — см. CLAUDE.md, §4).

create table if not exists report_periods (
  id          bigserial primary key,
  started_at  timestamptz not null unique,
  started_by  uuid references users(id),
  created_at  timestamptz not null default now()
);

alter table report_periods enable row level security;
