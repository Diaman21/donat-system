-- 0013: новый результат покупки — 🔐 verify («проверка данных»)
--
-- КОНТЕКСТ. 06.10.2026 на телефоне всплыл диалог Apple, которого раньше не было:
--   «Покупка не завершена. Отправьте запрос на проверку в службу поддержки
--    Apple.»  (кнопки «Дальше» / «Не сейчас»)
-- Apple требует подтвердить аккаунт и не даёт совершать покупки. Это НЕ ⚠️
-- support (там временный отказ платежа с отлёжкой ~сутки) и НЕ 💀 long
-- (waiver «vierzehn Tagen» = телефон мёртв). Записывать его как одно из них —
-- значит смешать три разных события и испортить аналитику коридора.
--
-- ⚠️ Деньги при verify НЕ списаны. Во всех суммах и в лимите €120 бот считает
-- только 'done', поэтому новое значение туда не попадает без правок.
-- ⚠️ Триггер handle_long_result реагирует только на 'long' — статус телефона
-- при verify НЕ меняется. Что происходит с телефоном после проверки, пока
-- неизвестно; если он потерян — вывод вручную через «☠️ Вывести» (forced).
--
-- ⚠️ ОТКАТИТЬ НЕЛЬЗЯ ПРОСТО: значение из enum в Postgres не удаляется.
-- Безвредно, пока его никто не использует, но назад — только пересозданием типа.
--
-- ⚠️ `add value` нельзя использовать в той же транзакции, где его добавили,
-- поэтому применяется отдельной командой, не внутри begin…commit.
--
-- Старый код с новым значением не ломается: он его никогда не пишет, а строк
-- с verify до деплоя нового кода не будет. Порядок: миграция → деплой.

alter type purchase_result add value if not exists 'verify';
