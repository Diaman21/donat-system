-- 0019: карта, привязанная для оплаты к телефону (последние 4 цифры)
--
-- КОНТЕКСТ (01.11.2026). При вводе телефона в работу владелец хочет записывать,
-- какая карта привязана к нему для оплаты, и видеть её на экране телефона
-- («Карта: 2850»). Бот спрашивает 4 цифры при вводе в работу (из резерва и сразу
-- новым), у телефонов, уже работающих к этому дню, — кнопкой «💳 Карта» в
-- «☎️ Телефоны»; той же кнопкой карту меняют.
--
-- Храним ТОЛЬКО последние 4 цифры — по ним номер карты не восстановить; так же
-- их показывают банки и магазины. CHECK не даёт записать ничего, кроме 4 цифр.
-- NULL — карта не указана (все телефоны до 01.11.2026 и резерв).

alter table phones
  add column if not exists card_last4 text
  check (card_last4 ~ '^[0-9]{4}$');
