-- ============================================================
-- Donat System — миграция 0009
-- Связь покупки с заказом из order_queue.
--
-- Почему НЕ переиспользуем purchases.order_id: у него внешний ключ на старую
-- пустую таблицу `orders` (наследие отвергнутой модели «доска заказов»),
-- туда id из order_queue не положить. Старую колонку не трогаем — она
-- остаётся NULL навсегда, как и было.
--
-- Колонка nullable: покупки БЕЗ заказа (разогрев €2, ВК) — норма, их большинство.
-- На аналитику «зелёного коридора» не влияет: в её запросах эта колонка не участвует.
-- ============================================================

alter table purchases
  add column order_queue_id uuid references order_queue(id);

-- Ищем «все покупки по заказу» — по нему и индекс (частичный: непустых мало).
create index purchases_order_queue_idx
  on purchases (order_queue_id)
  where order_queue_id is not null;
