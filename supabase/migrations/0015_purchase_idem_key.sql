-- 0015: ключ идемпотентности у покупки — защита от дубля
--
-- КОНТЕКСТ (аудит 07.10.2026). Правило проекта: «дубль опаснее потери» —
-- лишняя строка выглядит как настоящая покупка и молча портит коридор и
-- лимит суток. Две записи одной покупки сегодня возможны двумя путями:
--   1. Повторная доставка апдейта. Если обработка длится дольше таймаута
--      grammY (10 с), Telegram шлёт тот же апдейт снова — до десятков раз
--      (https://grammy.dev/guide/deployment-types).
--   2. Двойное нажатие на последнюю кнопку (📶/📡). Vercel (fluid compute)
--      умеет обрабатывать два запроса одновременно, и оба прочитают сессию
--      «ещё не записано» до того, как первый её сохранит.
-- По истории дублей у танков нет ни одного — риск теоретический, но
-- защита дешёвая.
--
-- ЧТО ДЕЛАЕТ. На экране подтверждения бот выдаёт потоку ввода одноразовый
-- ключ (UUID). Каждая строка покупки получает `<ключ>:<номер строки>`
-- (мультизакуп ВК пишет несколько строк одним запросом). Второй insert с теми
-- же ключами упирается в уникальный индекс и не проходит — бот отвечает
-- «уже записано».
--
-- Колонка nullable: у 570 старых покупок ключа нет и не будет. Обычный (не
-- частичный) уникальный индекс: NULL в Postgres друг другу не равны, поэтому
-- старым строкам он не мешает, а ON CONFLICT (idem_key) работает без условия.
--
-- Порядок: миграция → деплой кода. Старый код колонку не знает и не пишет —
-- ему она не мешает (все запросы к purchases перечисляют колонки явно).

alter table purchases add column if not exists idem_key text;
create unique index if not exists purchases_idem_key_uidx on purchases (idem_key);
