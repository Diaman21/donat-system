// Какие таблицы ссылаются на phones (12.11.2026). Чистая логика, без базы.
//
// Зачем: 01.11 появилась таблица accounts со ссылкой на телефон, а удаление
// подготовленного телефона о ней не знало — база отказывала (внешний ключ),
// и кнопка «🗑 Удалить» падала с «Что-то пошло не так». Ни один подготовленный
// телефон с аккаунтом удалить было нельзя.
//
// ⚠️ Страж: phone-refs.test.ts поднимает все миграции и сверяет этот список с
// настоящими внешними ключами на phones. Новая миграция со ссылкой на телефон
// уронит тест, пока сюда не впишут таблицу — и пока удаление телефона
// (phones.ts, onPreparedDeleteConfirm) не научат с ней обращаться.

/** Таблица → как её назвать человеку, если она мешает удалить телефон. */
export const PHONE_REFS: Record<string, string> = {
  purchases: 'покупки',
  advice_log: 'подсказки после покупок',
  card_ledger: 'запись бюджета (возврат)',
  accounts: 'аккаунт',
};

/**
 * Ошибка базы «на строку ещё ссылаются» (23503) → что мешает, по-человечески.
 * Не та ошибка — null. Драйвер может завернуть её в cause — смотрим оба уровня.
 */
export function fkBlocker(err: unknown): string | null {
  for (const e of [err, (err as { cause?: unknown } | null)?.cause]) {
    const x = e as { code?: string; table_name?: string } | null | undefined;
    if (x?.code === '23503') return (x.table_name && PHONE_REFS[x.table_name]) || 'связанные записи';
  }
  return null;
}
