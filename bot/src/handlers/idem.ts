import { randomUUID } from 'node:crypto';

// Ключ идемпотентности покупки — защита от дубля (миграция 0015).
//
// Ключ выдаётся ОДИН раз, когда оператор доходит до экрана подтверждения,
// и живёт в сессии вместе с потоком ввода. Всё, что приходит потом с тем же
// потоком, — повторная доставка апдейта Telegram или двойное нажатие на
// 📶/📡 — несёт тот же ключ, и уникальный индекс в базе не даёт записать
// покупку второй раз.
//
// Новая покупка — новый поток — новый ключ. Поэтому две НАСТОЯЩИЕ одинаковые
// покупки подряд (тот же телефон, та же сумма) записываются обе, как и должны.
//
// Чистый модуль (без БД) — проверяется тестом.

/** Новый ключ потока ввода. */
export function newIdem(): string {
  return randomUUID();
}

/**
 * Ключи для строк одной записи. Мультизакуп ВК пишет qty строк одним
 * запросом — у каждой свой ключ, иначе строки упёрлись бы друг в друга.
 */
export function idemKeys(idem: string, qty: number): string[] {
  return Array.from({ length: qty }, (_, i) => `${idem}:${i}`);
}
