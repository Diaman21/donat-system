// Текст предупреждения о повторе последних 4 цифр IMEI при добавлении телефона.
//
// Раньше бот проверял повтор только среди УМЕРШИХ. Совпадение с телефоном,
// который лежит в 🧰 резерве, не замечалось — и 07.10.2026 нашёлся дубль:
// …3977 «Красный 13» лежал в резерве с 11.09, а 18.09 тот же аппарат завели
// в работу заново как «13 красный». Он отработал цикл (€571) и был выведен,
// а резервная запись осталась. Взяли бы её «▶️ В работу» — телефон после
// полного цикла пошёл бы в аналитику как новый.
//
// Чистая функция (без БД) — чтобы текст можно было проверить тестом.

export interface PreparedTwin {
  label: string | null;
  /** Когда положен в резерв, уже отформатировано («11.09»). */
  since: string;
}

export interface DeadTwin {
  label: string | null;
  /** Когда умер, уже отформатировано. */
  when: string;
  /** Причина словами («ошибка Apple», «вынужденный вывод»…). */
  reason: string;
  /** Сколько всего умерших с этими цифрами. */
  count: number;
}

const lbl = (l: string | null) => (l ? ` «${l}»` : '');

/**
 * Сообщение о повторе IMEI. null — повтора нет, предупреждать не о чем.
 * Резерв идёт первым: это самый вероятный случай «тот же аппарат», и для
 * него есть действие лучше новой записи — взять его из резерва в работу.
 */
export function imeiRepeatNotice(
  imei: string,
  prepared: PreparedTwin[],
  dead: DeadTwin | null,
): string | null {
  if (prepared.length === 0 && !dead) return null;
  const out: string[] = [];

  if (prepared.length > 0) {
    out.push(
      prepared.length === 1
        ? `🧰 …${imei}${lbl(prepared[0]!.label)} уже лежит в подготовленных (с ${prepared[0]!.since}).`
        : `🧰 С цифрами …${imei} в подготовленных уже ${prepared.length} телефона:\n` +
            prepared.map((p) => `   • …${imei}${lbl(p.label)} — с ${p.since}`).join('\n'),
    );
  }

  if (dead) {
    const more = dead.count > 1 ? ` Всего таких в истории: ${dead.count}.` : '';
    out.push(
      `⚠️ На …${imei} уже работали${lbl(dead.label)}: умер ${dead.when} (${dead.reason}).${more}`,
    );
  }

  // Один ясный совет на каждый случай — не «возьми» и «не бери» одновременно.
  if (prepared.length > 0 && !dead) {
    out.push(
      'Скорее всего, это он. Возьми его из резерва кнопкой ниже — ' +
        'новая запись создаст дубль, и один аппарат посчитается за два.',
    );
  } else if (prepared.length > 0 && dead) {
    // Самый неприятный вариант: резервная запись аппарата, который уже
    // отработал цикл. Ровно так выглядел …3977 (07.10.2026).
    out.push(
      'Похоже, резервная запись — это аппарат, который уже отработал цикл. ' +
        'Такой в работу брать не стоит, а запись в резерве лучше удалить (🧰 → 🗑).',
    );
  }

  out.push(
    '',
    'Последние 4 цифры IMEI могут совпадать у разных аппаратов. ' +
      'Это тот же телефон или новый с теми же цифрами?',
  );
  return out.join('\n');
}
