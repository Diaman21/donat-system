import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  CORRIDOR_MIN_H,
  OPT_FROM_H,
  OPT_TO_H,
  nextPurchaseWindow,
  dayWord,
  nextPurchaseHint,
} from './interval.js';

// Тесты подсказки «когда можно следующую закупку».
//
// Зачем: это единственное место, где бот даёт оператору указание к действию.
// Ошибка в арифметике или в словах «сегодня/завтра» приведёт к нарушению
// протокола — а нарушение интервала исторически стоило втрое меньше денег
// (€242 против €839) и давало смертность до 36%.
//
// Все времена в тестах заданы в UTC явно; МСК = UTC+3.

const at = (iso: string) => new Date(iso);

// ---------- пороги ----------

test('пороги соответствуют протоколу из CLAUDE.md', () => {
  assert.equal(CORRIDOR_MIN_H, 20); // нижняя граница коридора
  assert.equal(OPT_FROM_H, 22); // рабочий оптимум 22–28 ч
  assert.equal(OPT_TO_H, 28);
  assert.ok(OPT_FROM_H > CORRIDOR_MIN_H, 'оптимум должен быть внутри коридора');
  assert.ok(OPT_TO_H <= 36, 'дальше 36 ч коридор кончается и начинаются убытки');
});

// ---------- арифметика окна ----------

test('окно считается от времени покупки', () => {
  const w = nextPurchaseWindow(at('2026-09-11T20:47:00.000Z')); // 23:47 МСК
  assert.equal(w.notBefore.toISOString(), '2026-09-12T16:47:00.000Z'); // +20 ч
  assert.equal(w.optFrom.toISOString(), '2026-09-12T18:47:00.000Z'); // +22 ч
  assert.equal(w.optTo.toISOString(), '2026-09-13T00:47:00.000Z'); // +28 ч
});

test('окно не зависит от часового пояса процесса', () => {
  // Считаем в миллисекундах от момента — перевод часов где-либо не влияет.
  const w = nextPurchaseWindow(at('2026-10-24T23:00:00.000Z'));
  assert.equal(w.notBefore.getTime() - at('2026-10-24T23:00:00.000Z').getTime(), 20 * 3600 * 1000);
});

// ---------- слова «сегодня / завтра» ----------

test('dayWord: сегодня / завтра / послезавтра', () => {
  const base = at('2026-09-11T09:00:00.000Z'); // 12:00 МСК 11.09
  assert.equal(dayWord(at('2026-09-11T18:00:00.000Z'), base), 'сегодня'); // 21:00 МСК 11.09
  assert.equal(dayWord(at('2026-09-12T09:00:00.000Z'), base), 'завтра');
  assert.equal(dayWord(at('2026-09-13T09:00:00.000Z'), base), 'послезавтра');
});

test('dayWord: дальше трёх дней — дата', () => {
  const base = at('2026-09-11T09:00:00.000Z');
  assert.equal(dayWord(at('2026-09-15T09:00:00.000Z'), base), '15.09');
});

// Ловушка: покупка поздно вечером по МСК. 21:30 UTC = 00:30 МСК СЛЕДУЮЩЕГО дня.
// Если считать «сегодня» по UTC, слово будет неверным на сутки.
test('dayWord: поздний вечер по МСК — день считается по Москве', () => {
  const base = at('2026-09-11T21:30:00.000Z'); // уже 00:30 МСК 12.09
  assert.equal(dayWord(at('2026-09-11T22:00:00.000Z'), base), 'сегодня'); // 01:00 МСК 12.09
  assert.equal(dayWord(at('2026-09-12T22:00:00.000Z'), base), 'завтра'); // 01:00 МСК 13.09
});

// ---------- готовое сообщение ----------

test('подсказка: реальный случай — €30 в 23:47 МСК', () => {
  // Именно так было у …2060 «Белый 16e» 11.09: вторая покупка за вечер.
  const lines = nextPurchaseHint(at('2026-09-11T20:47:00.000Z'));
  assert.equal(lines.length, 3);
  assert.ok(lines[0]?.includes('Следующая закупка'));
  // +22 ч = 21:47 МСК 12.09 (завтра), +28 ч = 03:47 МСК 13.09 (послезавтра)
  assert.equal(lines[1], '   🟢 лучше всего: завтра 21:47 — послезавтра 03:47');
  // +20 ч = 19:47 МСК 12.09
  assert.equal(lines[2], '   ⛔️ не раньше завтра 19:47 (раньше — зона риска)');
});

test('подсказка: оптимум внутри одних суток пишется коротко', () => {
  // 09:00 МСК → +22 ч = 07:00 следующего дня, +28 ч = 13:00 того же дня.
  const lines = nextPurchaseHint(at('2026-09-11T06:00:00.000Z'));
  assert.equal(lines[1], '   🟢 лучше всего: завтра 07:00–13:00');
});

test('подсказка: при незакрытом заказе просит взять другой телефон', () => {
  const lines = nextPurchaseHint(at('2026-09-11T20:47:00.000Z'), true);
  assert.equal(lines.length, 4);
  assert.ok(lines[3]?.includes('ДРУГОГО телефона'));
});

test('подсказка: без заказа лишней строки нет', () => {
  assert.equal(nextPurchaseHint(at('2026-09-11T20:47:00.000Z'), false).length, 3);
});

// Время «не раньше» обязано быть раньше начала оптимума — иначе подсказка
// противоречила бы сама себе.
test('подсказка внутренне непротиворечива на любом часе суток', () => {
  for (let h = 0; h < 24; h++) {
    const base = at(`2026-09-11T${String(h).padStart(2, '0')}:00:00.000Z`);
    const w = nextPurchaseWindow(base);
    assert.ok(w.notBefore < w.optFrom, `час ${h}: «не раньше» позже оптимума`);
    assert.ok(w.optFrom < w.optTo, `час ${h}: оптимум вывернут`);
    assert.equal(nextPurchaseHint(base).length, 3);
  }
});
