import type { AppContext } from '../context.js';
import { menuFor } from './menus.js';

export async function handleHelp(ctx: AppContext): Promise<void> {
  const text = [
    '🤖 Как пользоваться',
    '',
    '🛒 Закупка — записать покупку: телефон → игра → сумма € → результат (✅/⚠️/💀).',
    '➕📱 Телефон — привязать телефон (4 цифры IMEI + метка). Активных не больше 3.',
    '☎️ Телефоны — активные телефоны и сколько на каждый потрачено.',
    '📊 Статистика — сводка: €, покупки, телефоны, возраст до 💀.',
    '🗳 ВК — сводка голосов по дням на каждом телефоне (только просмотр).',
    '📋 Последние — последние закупки (проверить, что вбили верно).',
    '📜 /history — история конкретного телефона (таймлайн + заметки).',
    '❌ Удалить последнюю — откатить свою последнюю запись (если 💀 — телефон вернётся).',
    '',
    '📤 /report — отправить сводку (за неделю) в группу.',
    '📁 /export — выгрузка всех покупок в CSV (модератор).',
    '',
    'Команды: /start /stats /report /export /help /cancel',
    '',
    '💀 = телефон «умер»: больше не активен. ⚠️ = ошибка/саппорт. ✅ = успешно.',
    'Сумма $ — сколько реально потрачено через Apple Pay (главное для анализа).',
  ].join('\n');
  await ctx.reply(text, { reply_markup: menuFor(ctx) });
}
